import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const GTFS_URL = 'http://web.mta.info/developers/data/nyct/subway/google_transit.zip'
const STOPS_SOURCE_PATH =
  '/Users/cameron.boucher/Documents/signal-problems/supabase/functions/poll-mta/stops.ts'
const OUTPUT_PATH =
  '/Users/cameron.boucher/Documents/signal-problems/src/lib/mta-stations.ts'

function parseCsv(text) {
  const rows = []
  let row = []
  let value = ''
  let inQuotes = false

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i]
    const next = text[i + 1]

    if (char === '"') {
      if (inQuotes && next === '"') {
        value += '"'
        i += 1
      } else {
        inQuotes = !inQuotes
      }
      continue
    }

    if (char === ',' && !inQuotes) {
      row.push(value)
      value = ''
      continue
    }

    if ((char === '\n' || char === '\r') && !inQuotes) {
      if (char === '\r' && next === '\n') i += 1
      row.push(value)
      if (row.length > 1 || row[0] !== '') rows.push(row)
      row = []
      value = ''
      continue
    }

    value += char
  }

  if (value !== '' || row.length > 0) {
    row.push(value)
    rows.push(row)
  }

  return rows
}

function readStopsMap() {
  const file = readFileSync(STOPS_SOURCE_PATH, 'utf8')
  const matches = [...file.matchAll(/"([^"]+)": "([^"]+)"/g)]
  return new Map(matches.map(([, id, name]) => [id, name]))
}

function loadGtfsStops() {
  const tmpRoot = mkdtempSync(join(tmpdir(), 'mta-gtfs-'))
  const zipPath = join(tmpRoot, 'google_transit.zip')

  try {
    execFileSync('curl', ['-L', GTFS_URL, '-o', zipPath], { stdio: 'inherit' })
    const stopsCsv = execFileSync('unzip', ['-p', zipPath, 'stops.txt'], {
      encoding: 'utf8',
      maxBuffer: 20 * 1024 * 1024,
    })

    const [header, ...rows] = parseCsv(stopsCsv)
    if (!header) {
      throw new Error('GTFS stops.txt was empty')
    }

    return rows.map((row) => Object.fromEntries(header.map((key, index) => [key, row[index] ?? ''])))
  } finally {
    rmSync(tmpRoot, { recursive: true, force: true })
  }
}

function averageCoordinate(rows, field) {
  const values = rows
    .map((row) => Number.parseFloat(row[field]))
    .filter((value) => Number.isFinite(value))

  if (values.length === 0) return null
  return values.reduce((sum, value) => sum + value, 0) / values.length
}

function buildStations() {
  const stopNames = readStopsMap()
  const gtfsStops = loadGtfsStops()
  const rowsById = new Map(gtfsStops.map((row) => [row.stop_id, row]))
  const childrenByParent = new Map()

  for (const row of gtfsStops) {
    if (!row.parent_station) continue
    const existing = childrenByParent.get(row.parent_station) ?? []
    existing.push(row)
    childrenByParent.set(row.parent_station, existing)
  }

  const stations = []

  for (const [stopId, name] of stopNames.entries()) {
    const direct = rowsById.get(stopId)
    const parent = direct?.location_type === '1' ? direct : null
    const children = childrenByParent.get(stopId) ?? []
    const lat =
      parent && Number.isFinite(Number.parseFloat(parent.stop_lat))
        ? Number.parseFloat(parent.stop_lat)
        : averageCoordinate(children, 'stop_lat')
    const lon =
      parent && Number.isFinite(Number.parseFloat(parent.stop_lon))
        ? Number.parseFloat(parent.stop_lon)
        : averageCoordinate(children, 'stop_lon')

    if (!Number.isFinite(lat) || !Number.isFinite(lon)) {
      if (direct && Number.isFinite(Number.parseFloat(direct.stop_lat)) && Number.isFinite(Number.parseFloat(direct.stop_lon))) {
        stations.push({
          stopId,
          name,
          lat: Number.parseFloat(direct.stop_lat),
          lon: Number.parseFloat(direct.stop_lon),
        })
      }
      continue
    }

    stations.push({ stopId, name, lat, lon })
  }

  stations.sort((a, b) => a.stopId.localeCompare(b.stopId))
  return stations
}

function formatStationsFile(stations) {
  const entries = stations
    .map(
      ({ stopId, name, lat, lon }) =>
        `  ${JSON.stringify(stopId)}: { name: ${JSON.stringify(name)}, lat: ${lat.toFixed(6)}, lon: ${lon.toFixed(6)} },`,
    )
    .join('\n')

  return `// Auto-generated by scripts/generate-mta-stations.mjs
// Source: ${GTFS_URL}

export interface MtaStation {
  name: string
  lat: number
  lon: number
}

export const MTA_STATIONS: Record<string, MtaStation> = {
${entries}
}

export function getMtaStation(stopId: string): MtaStation | undefined {
  return MTA_STATIONS[stopId]
}
`
}

const stations = buildStations()
writeFileSync(OUTPUT_PATH, formatStationsFile(stations))

console.log(`Wrote ${stations.length} stations to ${OUTPUT_PATH}`)
